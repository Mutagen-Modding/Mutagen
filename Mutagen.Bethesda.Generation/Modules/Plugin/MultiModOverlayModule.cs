            // Constructor
            sb.AppendLine($"public MergedListGroup(IEnumerable<I{gameName}ListGroupGetter<ICellBlockGetter>> sourceGroups)");
            using (sb.CurlyBrace())
            {
                sb.AppendLine("_sourceGroups = sourceGroups;");
