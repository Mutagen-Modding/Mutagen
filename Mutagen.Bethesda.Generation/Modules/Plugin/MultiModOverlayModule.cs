            using (sb.CurlyBrace())
            {
                sb.AppendLine("var blocksByKey = new Dictionary<(short X, short Y), List<IWorldspaceBlockGetter>>();");
                sb.AppendLine("foreach (var ws in _allCopies)");
                using (sb.CurlyBrace())
